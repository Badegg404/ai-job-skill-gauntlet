#!/bin/bash
# ============================================================
# run_tests.sh — 一键运行测试集（后端 + 前端）
#
# 用法：./run_tests.sh
# 每次大改动后跑一遍，验证程序健康度。
# ============================================================
cd "$(dirname "$0")"

echo "=============================================="
echo "  🧪 测试集：验证程序健康度"
echo "=============================================="

echo ""
echo "=== 后端测试（Python unittest） ==="
python3 tests/test_backend.py
BACKEND=$?

echo ""
echo "=== 前端测试（Node） ==="
node tests/test_frontend.js
FRONTEND=$?

echo ""
echo "=============================================="
if [ "$BACKEND" -eq 0 ] && [ "$FRONTEND" -eq 0 ]; then
  echo "  ✅ 全部测试通过"
  echo "=============================================="
  exit 0
else
  echo "  ❌ 测试失败（后端:$BACKEND  前端:$FRONTEND）"
  echo "=============================================="
  exit 1
fi
